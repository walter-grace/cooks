/**
 * Diff Cooks' OpenAPI document against the vendored upstream contract.
 * Reports: upstream operations missing in Cooks, upstream query params missing per operation,
 * upstream response fields missing from our component schemas, and Cooks-only operations
 * (which must be tagged as extensions). Writes docs/conformance.md and returns a summary.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { parse as parseYaml } from 'yaml';

type Doc = {
  paths: Record<string, Record<string, { operationId?: string; tags?: string[]; parameters?: Array<{ name?: string; in?: string; $ref?: string }>; responses?: Record<string, unknown> }>>;
  components?: { schemas?: Record<string, { properties?: Record<string, unknown>; required?: string[] }>; parameters?: Record<string, { name: string; in: string }> };
};

export interface ConformanceReport {
  missingOperations: string[];
  missingParams: Array<{ op: string; params: string[] }>;
  missingFields: Array<{ schema: string; fields: string[] }>;
  untaggedExtensions: string[];
  extensions: string[];
  upstreamOps: number;
  matchedOps: number;
}

const METHODS = ['get', 'post', 'patch', 'put', 'delete'];

function ops(doc: Doc, stripPrefix = '') {
  const out = new Map<string, { path: string; method: string; op: Doc['paths'][string][string] }>();
  for (const [p, methods] of Object.entries(doc.paths ?? {})) {
    const path = stripPrefix && p.startsWith(stripPrefix) ? p.slice(stripPrefix.length) : p;
    for (const m of METHODS) {
      const op = methods[m];
      if (op) out.set(`${m.toUpperCase()} ${path}`, { path, method: m, op });
    }
  }
  return out;
}

function paramNames(doc: Doc, op: Doc['paths'][string][string]): string[] {
  return (op.parameters ?? [])
    .map((p) => {
      if (p.$ref) {
        const name = p.$ref.split('/').pop()!;
        const c = doc.components?.parameters?.[name];
        return c?.in === 'query' ? c.name : null;
      }
      return p.in === 'query' ? (p.name ?? null) : null;
    })
    .filter((n): n is string => !!n);
}

export function compare(upstream: Doc, ours: Doc): ConformanceReport {
  const up = ops(upstream);
  const mine = ops(ours);
  const missingOperations: string[] = [];
  const missingParams: ConformanceReport['missingParams'] = [];
  let matched = 0;
  for (const [key, u] of up) {
    const m = mine.get(key);
    if (!m) {
      missingOperations.push(`${key} (${u.op.operationId ?? '?'})`);
      continue;
    }
    matched++;
    const want = new Set(paramNames(upstream, u.op));
    const have = new Set(paramNames(ours, m.op));
    const missing = [...want].filter((w) => !have.has(w));
    if (missing.length) missingParams.push({ op: key, params: missing });
  }
  const extensions: string[] = [];
  const untaggedExtensions: string[] = [];
  for (const [key, m] of mine) {
    if (up.has(key)) continue;
    extensions.push(`${key} (${m.op.operationId ?? '?'})`);
    if (!(m.op.tags ?? []).includes('Cooks extensions')) untaggedExtensions.push(key);
  }
  const missingFields: ConformanceReport['missingFields'] = [];
  for (const [name, schema] of Object.entries(upstream.components?.schemas ?? {})) {
    const oursSchema = ours.components?.schemas?.[name];
    if (!oursSchema || !schema.properties) continue;
    const want = Object.keys(schema.properties);
    const have = new Set(Object.keys(oursSchema.properties ?? {}));
    const missing = want.filter((w) => !have.has(w));
    if (missing.length) missingFields.push({ schema: name, fields: missing });
  }
  return { missingOperations, missingParams, missingFields, untaggedExtensions, extensions, upstreamOps: up.size, matchedOps: matched };
}

export function renderMarkdown(r: ConformanceReport, meta: { upstreamSha: string; fetchedAt: string }): string {
  const lines = [
    '# API conformance report',
    '',
    `Generated by \`pnpm conformance\`. Upstream spec sha256 \`${meta.upstreamSha.slice(0, 12)}\` fetched ${meta.fetchedAt}.`,
    '',
    `| Metric | Value |`,
    `| --- | --- |`,
    `| Upstream operations | ${r.upstreamOps} |`,
    `| Implemented | ${r.matchedOps} |`,
    `| Missing | ${r.missingOperations.length} |`,
    `| Operations with missing query params | ${r.missingParams.length} |`,
    `| Schemas with missing fields | ${r.missingFields.length} |`,
    `| Cooks-only operations | ${r.extensions.length} |`,
    '',
  ];
  const section = (title: string, items: string[]) => {
    lines.push(`## ${title}`, '');
    lines.push(...(items.length ? items.map((i) => `- ${i}`) : ['_none_']), '');
  };
  section('Missing upstream operations', r.missingOperations);
  section('Missing query parameters', r.missingParams.map((m) => `\`${m.op}\`: ${m.params.join(', ')}`));
  section('Missing schema fields', r.missingFields.map((m) => `\`${m.schema}\`: ${m.fields.join(', ')}`));
  section('Cooks extensions (not in upstream)', r.extensions);
  if (r.untaggedExtensions.length) section('Extensions missing the "Cooks extensions" tag', r.untaggedExtensions);
  return lines.join('\n');
}

export async function buildOurDoc(): Promise<Doc> {
  const { createTestDb } = await import('@cooks/db/test');
  const { createApp } = await import('../apps/api/src/app.js');
  const t = await createTestDb();
  try {
    const { app } = createApp({ db: t.db });
    const res = await app.request('/openapi.json');
    return (await res.json()) as Doc;
  } finally {
    await t.close();
  }
}

export function loadUpstream(): { doc: Doc; sha: string; fetchedAt: string } {
  const doc = parseYaml(readFileSync(new URL('../spec/nooks-upstream.openapi.yml', import.meta.url), 'utf8')) as Doc;
  const lock = JSON.parse(readFileSync(new URL('../spec/upstream.lock.json', import.meta.url), 'utf8')) as { sha256: string; fetchedAt: string };
  return { doc, sha: lock.sha256, fetchedAt: lock.fetchedAt };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop()!)) {
  const up = loadUpstream();
  const ours = await buildOurDoc();
  const report = compare(up.doc, ours);
  const md = renderMarkdown(report, { upstreamSha: up.sha, fetchedAt: up.fetchedAt });
  writeFileSync(new URL('../docs/conformance.md', import.meta.url), md);
  console.log(md);
  if (report.missingOperations.length || report.untaggedExtensions.length) process.exit(1);
}
